def wavelength_to_rgb(nm):
    nm = float(nm)
    if 380 <= nm < 440: R, G, B = -(nm-440)/(440-380), 0.0, 1.0
    elif 440 <= nm < 490: R, G, B = 0.0, (nm-440)/(490-440), 1.0
    elif 490 <= nm < 510: R, G, B = 0.0, 1.0, -(nm-510)/(510-490)
    elif 510 <= nm < 580: R, G, B = (nm-510)/(580-510), 1.0, 0.0
    elif 580 <= nm < 645: R, G, B = 1.0, -(nm-645)/(645-580), 0.0
    elif 645 <= nm <= 780: R, G, B = 1.0, 0.0, 0.0
    else: R, G, B = 0.0, 0.0, 0.0

    f = 1.0
    if 380 <= nm < 420: f = 0.3 + 0.7*(nm-380)/(420-380)
    elif 645 < nm <= 780: f = 0.3 + 0.7*(780-nm)/(780-645)

    return [int(255 * (c * f)**0.8) for c in (R, G, B)]